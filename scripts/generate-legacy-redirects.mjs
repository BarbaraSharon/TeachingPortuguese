import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, sep } from 'node:path';

const SITE_ORIGIN = 'https://barbarasharon.com.au';
const projectRoot = process.cwd();
const checkOnly = process.argv.includes('--check');
const positionalArgs = process.argv.slice(2).filter((arg) => arg !== '--check');
const manifestPath = resolve(projectRoot, positionalArgs[0] ?? 'data/legacy-redirects.json');
const outputRoot = resolve(projectRoot, positionalArgs[1] ?? 'public');

const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));

if (!Array.isArray(manifest.redirects)) {
  throw new Error('Legacy redirect manifest must contain a redirects array.');
}

if (manifest.redirects.length !== manifest.expectedSourceUrlCount) {
  throw new Error(
    `Legacy redirect count changed: expected ${manifest.expectedSourceUrlCount}, found ${manifest.redirects.length}.`,
  );
}

const seenSources = new Set();

function validateRoute(route, label) {
  if (typeof route !== 'string' || !route.startsWith('/') || !route.endsWith('/')) {
    throw new Error(`${label} must start and end with a slash: ${route}`);
  }
  if (route.includes('..') || route.includes('?') || route.includes('#') || route.includes('\\')) {
    throw new Error(`${label} contains an unsafe path component: ${route}`);
  }
}

function outputFileForRoute(route) {
  const relativeRoute = route === '/' ? '' : route.slice(1, -1);
  const outputFile = resolve(outputRoot, relativeRoute, 'index.html');
  if (outputFile !== resolve(outputRoot, 'index.html') && !outputFile.startsWith(`${outputRoot}${sep}`)) {
    throw new Error(`Redirect output escapes the public directory: ${route}`);
  }
  return outputFile;
}

function escapeHtml(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function renderRedirect(destination) {
  const escapedPath = escapeHtml(destination);
  const escapedCanonical = escapeHtml(`${SITE_ORIGIN}${destination}`);
  return `<!doctype html>
<html lang="en-AU">
  <head>
    <meta charset="utf-8">
    <meta name="robots" content="noindex, follow">
    <meta http-equiv="refresh" content="0; url=${escapedPath}">
    <link rel="canonical" href="${escapedCanonical}">
    <title>Redirecting to Barbara Sharon</title>
  </head>
  <body>
    <h1>Redirecting to Barbara Sharon</h1>
    <p>This page has moved to <a href="${escapedPath}">${escapedPath}</a>.</p>
    <script>window.location.replace(${JSON.stringify(destination)});</script>
  </body>
</html>
`;
}

function renderRootRedirect() {
  return `<!doctype html>
<html lang="en-AU">
  <head>
    <meta charset="utf-8">
    <meta name="robots" content="noindex, follow">
    <meta name="description" content="Learn Brazilian Portuguese with Barbara Sharon through private and group lessons online or on the Gold Coast.">
    <meta http-equiv="refresh" content="0; url=/en/">
    <link rel="canonical" href="${SITE_ORIGIN}/en/">
    <meta property="og:site_name" content="Learn Portuguese with Barbara Sharon">
    <meta property="og:type" content="website">
    <meta property="og:url" content="${SITE_ORIGIN}/en/">
    <meta property="og:title" content="Learn Portuguese with Barbara Sharon">
    <meta property="og:description" content="Learn Brazilian Portuguese with Barbara Sharon through private and group lessons online or on the Gold Coast.">
    <meta property="og:image" content="${SITE_ORIGIN}/media/barbara-sharon.jpg">
    <title>Learn Portuguese with Barbara Sharon</title>
  </head>
  <body>
    <p><a href="/en/">Learn Portuguese with Barbara Sharon</a></p>
    <script>window.location.replace('/en/');</script>
  </body>
</html>
`;
}

const rootRedirectFile = resolve(outputRoot, 'index.html');
const rootRedirectHtml = renderRootRedirect();
if (checkOnly) {
  const actualRootHtml = await readFile(rootRedirectFile, 'utf8');
  if (actualRootHtml !== rootRedirectHtml) {
    throw new Error('Root language redirect is stale or incomplete.');
  }
} else {
  await writeFile(rootRedirectFile, rootRedirectHtml, 'utf8');
}

for (const redirect of manifest.redirects) {
  const { from, to } = redirect;
  validateRoute(from, 'Redirect source');
  validateRoute(to, 'Redirect destination');

  if (from.startsWith('/en/')) {
    throw new Error(`Legacy redirect must not overwrite a canonical English page: ${from}`);
  }
  if (!to.startsWith('/en/')) {
    throw new Error(`Legacy redirect destination must be a current English URL: ${to}`);
  }
  if (seenSources.has(from)) {
    throw new Error(`Duplicate legacy redirect source: ${from}`);
  }
  seenSources.add(from);

  const targetFile = outputFileForRoute(to);
  try {
    await readFile(targetFile, 'utf8');
  } catch {
    throw new Error(`Redirect destination was not generated by Hugo: ${to}`);
  }

  const redirectFile = outputFileForRoute(from);
  const expectedHtml = renderRedirect(to);

  if (checkOnly) {
    let actualHtml;
    try {
      actualHtml = await readFile(redirectFile, 'utf8');
    } catch {
      throw new Error(`Legacy redirect page is missing: ${from}`);
    }
    if (actualHtml !== expectedHtml) {
      throw new Error(`Legacy redirect page is stale or points to the wrong target: ${from}`);
    }
  } else {
    await mkdir(resolve(redirectFile, '..'), { recursive: true });
    await writeFile(redirectFile, expectedHtml, 'utf8');
  }
}

const action = checkOnly ? 'Verified' : 'Generated';
console.log(
  `${action} ${manifest.redirects.length} legacy redirects from commit ${manifest.sourceCommit}.`,
);
